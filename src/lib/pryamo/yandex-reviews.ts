/**
 * Анализ отзывов о Яндекс Go (пассажиры) и Яндекс Про (водители)
 * из App Store и Google Play — основа раздела «Отзывы Яндекса → ДНК ПРЯМО».
 *
 * Методика: выгрузка свежих отзывов из открытых фидов App Store (RU) и
 * разборов отзывов Google Play (otzovik/irecommend/oborot) за октябрь–ноябрь
 * 2026. Каждая категория — с реальной цитатой (обезличено, без правок смысла).
 * Позитив — то, что в ПРЯМО повторяем; негатив — то, что устраняем
 * архитектурой (не «пообещаем в поддержке», а убираем причину в продукте).
 */

export interface ReviewSource {
  app: string
  platform: string
  url: string
  packageId: string
}

export interface ReviewCategory {
  /** Код категории (для якорей/ключей) */
  id: string
  /** Название категории как её формулирует пользователь */
  title: string
  /** Сколько раз встретилось в выборке (≈) */
  count: number
  /** Позитив — повторяем; негатив — устраняем */
  kind: 'positive' | 'negative'
  /** Реальная цитата из отзыва (обезличено) */
  quote: string
  /** Кто сказал: пассажир или водитель */
  who: 'Пассажир' | 'Водитель'
  /** Дата цитаты */
  quoteDate: string
  /** Что делает ПРЯМО */
  pryamo: string
  /** Код статуса внедрения */
  status: 'done' | 'roadmap'
}

