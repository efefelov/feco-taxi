function pngSize(buf) { return { w: buf.readUInt32BE(16), h: buf.readUInt32BE(20) }; }
function figure(path, caption, displayWidth = 560) {
  const buf = fs.readFileSync(path);
  const { w, h } = pngSize(buf);
  const displayHeight = Math.round(displayWidth * h / w);
  return [
    new Paragraph({
      alignment: AlignmentType.CENTER, spacing: { before: 160, after: 60 }, keepNext: true,
      children: [new ImageRun({ data: buf, transformation: { width: displayWidth, height: displayHeight }, type: "png" })],
    }),
    new Paragraph({
      alignment: AlignmentType.CENTER, spacing: { after: 160, line: 276 },
      children: [new TextRun({ text: caption, size: 21, color: P.secondary, font: CYR_BODY })],
    }),
  ];
}

